package br.com.fieldshift.core.modelo;

/** O papel de uma época do ano na rotação. */
public enum Fase {
    /** Colheita principal, na época que mais chove. */
    SAFRA,
    /** Segunda colheita do ano, com uma planta de ciclo curto. */
    SAFRINHA,
    /** Época seca: a terra fica com planta de cobertura, sem colheita. */
    ENTRESSAFRA
}
